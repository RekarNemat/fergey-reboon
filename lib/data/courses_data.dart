  for (final entry in courseCatalog.entries) {
    if (courseTitleOrKey.contains(entry.key) ||
        entry.key.contains(courseTitleOrKey)) {
      return entry.value;
    }
  }
  return CourseDetail(
    key: courseTitleOrKey,
    title: courseTitleOrKey,
    instructor: 'ئەکادیمیای ڕێبوون',
    episodesCount: 6,
    category: 'وانەی شەرعی',
    summary: 'دیراسە و شیکردنەوەی مەتنی $courseTitleOrKey لە فێرگەی ڕێبوون.',
    accentColor: AppColors.teal700,
